const recent = {};
/** 依類別抽一句（避開最近 5 次）；rand 可注入 */
export function pickPhrase(kind, rand = Math.random) {
  const list = PHRASES[kind] || [];
  if (!list.length) return '';
  const used = recent[kind] || (recent[kind] = []);
  const pool = list.filter((p) => !used.includes(p));
  const pick = (pool.length ? pool : list)[Math.floor(rand() * (pool.length ? pool.length : list.length))];
  used.push(pick);
  while (used.length > Math.min(5, list.length - 1)) used.shift();
  return pick;
}

